""" 
Случайная строка 🎲
Напишите функцию get_random_string(filename), которая принимает название файла 
и возвращает случайную строку из этого файла (с удаленным символом перевода на новую строку).

Примечание 1. 
Считайте, что исполняемая программа и указанный файл находятся в одной папке.

Примечание 2. 
Гарантируется, что файл содержит хотя бы одну строку.

Примечание 3. 
Не забудьте закрыть файл. 🙂

Примечание 4.
Приведенные ниже тесты – это лишь примеры ответа. Возможны и другие варианты выбора строки.

Примечание 5. 
Вызывать функцию get_random_string() не нужно, требуется только реализовать ее.
"""


import random
def get_random_string(filename):
    file = open(filename, 'r', encoding='utf-8')
    lines = file.read().splitlines()
    file.close()
    return random.choice(lines)
