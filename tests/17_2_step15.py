""" 
Сумма всех
Вам доступен текстовый файл, состоящий из нескольких строк, в каждой из которых записано целое число.
Напишите программу, которая принимает на вход название файла и выводит сумму чисел из всех строк этого файла.

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести сумму чисел из всех строк указанного файла.

Примечание 1. 
Считайте, что исполняемая программа и указанный файл находятся в одной папке.

Примечание 2.
Не забудьте закрыть файл. 🙂
"""


file_name = input()

file = open(file_name, 'r', encoding='utf-8')

content = list(map(int, file.read().split()))

print(sum(content))

file.close()
