""" 
Напишите функцию call(), которая принимает произвольную функцию и аргументы для нее 
и делает вызов переданной функции, возвращая ее значение.

Примечание. 
Вызывать функцию call() не нужно, требуется только реализовать ее.
"""


def call(func, *args, **kwargs):
    return func(*args, **kwargs)


def func2(x, y):
    return str(x**10) + 2 * str(y)


print(call(func2, 20, 71))
