""" 
Сумма чисел в строках
Вам доступен текстовый файл, каждая строка которого может содержать одно или несколько целых чисел,
разделенных одним или несколькими пробелами.

Напишите программу, которая принимает на вход строку с именем текстового файла, 
вычисляет сумму чисел в каждой строке этого файла 
и выводит эту сумму на экран (для каждой строки сумма чисел выводится в отдельной строке).

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести сумму чисел для каждой строки.

Примечание. 
Считайте, что исполняемая программа и указанный файл находятся в одной папке.
"""


filename = input()

with open(filename, 'r', encoding='utf-8') as file:
    for line in file:
        # split() без аргументов разбивает по любым пробельным символам и игнорирует лишние пробелы
        numbers = map(int, line.split())
        print(sum(numbers))
