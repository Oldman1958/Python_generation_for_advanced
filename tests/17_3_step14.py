""" 
Статистика по файлу 📊
Вам доступен текстовый файл, набранный латиницей. 
Напишите программу, которая принимает название файла 
и выводит для него количество букв латинского алфавита, слов и строк в следующем формате:

Input file contains:
<кол-во букв> letters
<кол-во слов> words
<кол-во строк> lines

                  
Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести текст в соответствии с условием задачи.

Примечание 1. Считайте, что исполняемая программа и указанный файл находятся в одной папке.

Примечание 2. Словом называется последовательность из непробельных символов. 
Например, следующая строка:
abc a21 67pop    qwert bo7ok 83456
                  
содержит 6 слов: abc, a21, 67pop, qwert, bo7ok, 83456.
"""

filename = input()

with open(filename, 'r', encoding='utf-8') as file:
    lines = file.readlines()

# Количество строк — это просто число прочитанных строк
num_lines = len(lines)

num_letters = 0
num_words = 0

for line in lines:
    # Считаем латинские буквы (a–z, A–Z)
    for char in line:
        if ('a' <= char <= 'z') or ('A' <= char <= 'Z'):
            num_letters += 1

    # Слова — последовательности непробельных символов.
    # split() без аргументов разбивает по любым пробельным символам и игнорирует пустые фрагменты.
    words_in_line = line.split()
    num_words += len(words_in_line)

print(f"Input file contains:")
print(f"{num_letters} letters")
print(f"{num_words} words")
print(f"{num_lines} lines")
