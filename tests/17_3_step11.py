""" 
Длинные строки ↔️
Вам доступен текстовый файл, в котором записаны строки текста. 
Напишите программу, которая принимает на вход строку с именем текстового файла 
и выводит все строки наибольшей длины из файла, не меняя их порядок, с удаленным символом перевода на новую строку.

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести строки указанного файла, имеющие наибольшую длину, не меняя их порядка.

Примечание 1. 
Считайте, что исполняемая программа и указанный файл находятся в одной папке.

Примечание 2. 
Используйте менеджер контекста. 🙂
"""

file_name = input()

with open(file_name, 'r', encoding='utf-8') as file:
    lines = file.read().splitlines()

    max_length = max(map(len, lines))

    for line in lines:
        if len(line) == max_length:
            print(line)
