""" 
Вам доступен список numbers, содержащий целые числа. 
Напишите программу, которая удаляет из списка все числа-палиндромы и печатает результат на одной строке через пробел.

Примечание 1. 
Считайте, что список numbers уже объявлен в вашей программе, и вы имеете к нему доступ.

Примечание 2.
Вспомните про встроенную функцию filter() и анонимные функции lambda.

Примечание от меня.
Число-палиндром — это натуральное число, которое одинаково читается слева направо и справа налево. 
Иными словами, его запись симметрична: цифры зеркально отражают друг друга относительно центра. 
При этом количество цифр в числе может быть как чётным, так и нечётным. 
"""


numbers = [1, 72, 2, 3, 84, 15]

print(*list(filter(lambda x: str(x) != str(x)[::-1], numbers)))
