""" 
Напишите функцию concat(), принимающую переменное количество аргументов и объединяющую их в одну строку через разделитель (sep). 
Если разделитель не задан, им служит пробел.

Примечание 1. 
Обратите внимание: функция concat() должна принимать не список, а именно переменное количество аргументов.

Примечание 2. 
Вызывать функцию concat() не нужно, требуется только реализовать ее.
"""


def concat(*args, sep=' '):
    return sep.join(str(item) for item in args)


print(concat('hello', 'python', 'and', 'stepik'))
