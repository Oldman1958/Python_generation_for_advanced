""" 
Напишите функцию func(), используя синтаксис анонимных функций,
которая принимает целочисленный аргумент и возвращает значение True, 
если он делится без остатка на 19 или на 13, или False в противном случае.

Примечание. 
Вызывать функцию func() не нужно, требуется только реализовать ее.
"""


func = lambda x: True if x % 19 == 0 or x % 13 == 0 else False


print(func(19))
print(func(13))
print(func(4))
