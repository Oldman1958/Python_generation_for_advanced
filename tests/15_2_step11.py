""" 
Напишите функцию sq_sum(), 
которая принимает произвольное количество числовых аргументов
и возвращает сумму их квадратов.

Примечание 1.
Обратите внимание: функция должна принимать не список, 
а именно произвольное количество аргументов.

Примечание 2. 
Вызывать функцию sq_sum() не нужно, требуется только реализовать ее.
"""

def sq_sum(*args):
    return sum([i**2 for i in args])


print(sq_sum(1.5, 2.5))
