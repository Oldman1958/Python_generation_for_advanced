""" 
Вам доступен список mixed_list, содержащий целочисленные и строковые значения. 
Напишите программу его сортировки по неубыванию значений элементов, при этом числа должны следовать до строк. 
Элементы отсортированного списка выведите на одной строке, разделив символом пробела.

Примечание 1. 
Для решения задачи используйте анонимную функцию и необязательный аргумент key  функции sorted().

Примечание 2. 
Считайте, что список mixed_list уже объявлен в вашей программе, и вы имеете к нему доступ.
"""


mixed_list = ['a', 'ab', 3, 5, 1, 8, 0, 'c', 'ac', 'aab']

print(*sorted(mixed_list, key=lambda x: (0, x) if isinstance(x, int) else (1, str(x))))
