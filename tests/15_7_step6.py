""" 
Напишите функцию func(), используя синтаксис анонимных функций,
которая принимает строковый аргумент и возвращает значение True, 
если переданный аргумент начинается и заканчивается на английскую букву a 
(регистр буквы неважен), или False в противном случае.

Примечание. Вызывать функцию func() не нужно, требуется только реализовать ее.
"""


func = lambda x: x.lower()[0] == 'a' and x.lower()[-1] == 'a' 


print(func('abcd'))
print(func('bcda'))
print(func('abcda'))
