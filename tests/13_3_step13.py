""" 
Операции над комплексными числами
Даны два комплексных числа. 
Напишите программу, которая вычисляет и выводит их сумму, разность и произведение.
"""

# Считываем два комплексных числа в формате a+bj (например, 2+3j)
z1 = complex(input())
z2 = complex(input())

# Вычисляем операции
sum_z = z1 + z2
diff_z = z1 - z2
prod_z = z1 * z2

# Выводим результаты
print(f'{z1} + {z2} = {sum_z}')
print(f'{z1} - {z2} = {diff_z}')
print(f'{z1} * {z2} = {prod_z}')
