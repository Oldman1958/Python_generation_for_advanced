""" 
Вам доступен список points, содержащий кортежи координат точек плоскости. 
Напишите программу, которая сортирует список points в соответствии с расстоянием точки до начала координат 
(точки (0;0)). Программа должна вывести отсортированный список.
"""

points = [(3, 4), (-2, 1), (0, 1), (5, 12)]

sorted_points = sorted(points, key=lambda p: p[0]**2 + p[1]**2)
print(sorted_points)
