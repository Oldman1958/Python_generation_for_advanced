""" 
Вам доступен список mixed_list, содержащий целочисленные и строковые значения. 
Напишите программу, которая с помощью встроенной функции max() 
находит и выводит наибольшее числовое значение в указанном списке.

Примечание 1. 
Для решения задачи используйте анонимную функцию и необязательный аргумент key функции max().

Примечание 2. 
Обратите внимание: сравнивать числа и строки в Python нельзя.

Примечание 3. 
Считайте, что список mixed_list уже объявлен в вашей программе, и вы имеете к нему доступ.
"""

# mixed_list = ['cow', 12, 'chicken', 'sand', 75]

mixed_list = ['space', 45, 'land', 'cruelty', 634]

print(max(mixed_list, key=lambda x: x if isinstance(x, int) else float('-inf')))

