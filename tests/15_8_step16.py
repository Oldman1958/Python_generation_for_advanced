""" 
Значение многочлена 🌶️
Многочленом степени n называется выражение вида 

***************************************************
Тут формула, которую я не смог ввести в ВС Коде, ищите сами :)
***************************************************

На вход программе на первой строке подаются коэффициенты многочлена, разделенные символом пробела и целое число x на второй строке.
Напишите программу, которая вычисляет значение указанного многочлена при заданном значении x.

Формат входных данных
На вход программе на первой строке подаются коэффициенты многочлена (целые числа),
разделенные символом пробела и целое число x на второй строке.

Формат выходных данных
Программа должна вывести одно число — значение указанного многочлена при заданном значении x.

Примечание 1. 
Первый тест задает многочлен 2x^2+4x+3,
второй тест задает многочлен x^6+2x^5+3x^4+4x^3+5x^2+6x+7.

Примечание 2.
Решение задачи необходимо оформить в виде функции evaluate(coefficients, x), 
которая принимает список коэффициентов и значение аргумента. 
Функция evaluate() должна быть реализована на основе встроенных функций map() и reduce().

Примечание 3. 
Не забудьте вызвать функцию evaluate(), чтобы вывести результат 😀.
"""

from functools import reduce


def evaluate(coefficients, x):
    # Степени: первый коэффициент — при самой старшей степени
    powers = map(lambda i: x ** i, range(len(coefficients) - 1, -1, -1))
    # Складываем произведения коэффициентов на соответствующие степени x
    return reduce(lambda acc, pair: acc + pair[0] * pair[1],
                  zip(coefficients, powers), 0)


coefficients = list(map(int, input().split()))
x = int(input())
print(evaluate(coefficients, x))
