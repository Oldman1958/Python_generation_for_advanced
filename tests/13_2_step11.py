""" 
Сумма дробей 2
На вход программе подается натуральное число n.
Напишите программу, которая вычисляет и выводит рациональное число, 
равное значению выражения:

1/1!+1/2!+1/3!+1/4!+…+1/n!

Формат входных данных
На вход программе подается натуральное число n.

Формат выходных данных
Программа должна вывести ответ на задачу.

Примечание 1. Результирующая дробь должна быть несократимой.

Примечание 2. Для вычисления факториала можно использовать функцию factorial из модуля math.
"""

from fractions import Fraction

n = int(input())
total = Fraction(0, 1)
factorial = 1

for i in range(1, n + 1):
    factorial *= i          # вычисляем i!
    total += Fraction(1, factorial)

print(total)

