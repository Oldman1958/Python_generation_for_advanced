""" 
Сумма чисел в файле
Вам доступен текстовый файл, в котором могут быть записаны цифры, буквы и пробелы. 
Числом назовем последовательность одной и более цифр, идущих подряд (число всегда неотрицательно).

Напишите программу, которая принимает на вход название файла и вычисляет сумму всех чисел, записанных в нем.

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести сумму всех чисел, записанных в файле.

Примечание. 
Считайте, что исполняемая программа и указанный файл находятся в одной папке.
"""

filename = input()

with open(filename, 'r', encoding='utf-8') as file:
    text = file.read()

total_sum = 0
current_number = ''

for char in text:
    if char.isdigit():
        # Накапливаем цифры в строку — формируем число
        current_number += char
    else:
        # Встретили не цифру — если до этого набирали число, добавляем его к сумме
        if current_number:
            total_sum += int(current_number)
            current_number = ''

# Если файл заканчивается цифрой, число ещё не добавлено — учтём его
if current_number:
    total_sum += int(current_number)

print(total_sum)
