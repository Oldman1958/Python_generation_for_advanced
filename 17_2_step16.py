""" 
Общая стоимость 💰
Вам доступен текстовый файл с информацией о заказе из интернет-магазина.
В этом файле каждая строка с помощью символа табуляции (\t) разделена на три колонки:

наименование товара
количество товара (целое число)
цена (в рублях) товара за 1 шт (целое число)

Напишите программу, которая принимает на вход название файла и выводит общую стоимость заказа из этого файла.

Формат входных данных
На вход программе подается строка текста с именем существующего текстового файла.

Формат выходных данных
Программа должна вывести общую стоимость заказа.

Примечание 1. 
Считайте, что исполняемая программа и указанный файл находятся в одной папке.

Примечание 2. 
Не забудьте закрыть файл. 🙂
"""


filename = input().strip()
total = 0

file = open(filename, 'r', encoding='utf-8')

for line in file:
    name, quantity, price = line.strip().split('\t')
    total += int(quantity) * int(price)

print(total)
